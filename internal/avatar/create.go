// Result sources (API-AVT-001).
const (
	SourceModel = "model"
	SourceLocal = "local"
)

// CallSource is the router call-record source of a generation (REQ-AVT-002).
const CallSource = llmcall.SourceAvatar

// maxTokens bounds a model reply; an avatar is well under 8 KB.
const maxTokens = 1500

// attemptTimeout bounds one model call.
const attemptTimeout = 60 * time.Second

// ErrClaudeCodeModel is returned when the requested model runs in Claude
// Code, which cannot answer a plain completion (REQ-AVT-002).
var ErrClaudeCodeModel = errors.New("avatars cannot be generated by a Claude Code model")

// ErrUnknownModel is returned when the requested model names no combo or
// known provider address.
var ErrUnknownModel = llmcall.ErrUnknownModel

// Request is one generation.
type Request struct {
	// Agent is the agent name, for the call record.
	Agent string
	// Config is the agent's config; its background chain is used when Model
	// is empty.
	Config core.AgentConfig
	// Model is a combo or "provider/model" address, or "" for the agent's
	// background model.
	Model string
	// Seed picks the body family and, for the local generator, the drawing.
	Seed int64
}

// Result is a generated avatar (API-AVT-001).
type Result struct {
	SVG string
	// Model is the address that answered, "" for a local result.
	Model  string
	Seed   int64
	Source string
}

// Create generates an avatar (REQ-AVT-002, REQ-AVT-005): it asks the model
// (or the agent's background chain) for an SVG of a randomly chosen family
// and sanitizes it; a failed call or an invalid SVG is retried once with a
// new seed, and then the local generator draws one. Without any non-Claude
// model the local generator answers at once. Only a requested model that is
// Claude Code or unknown is an error.
func Create(ctx context.Context, llm core.LLMRegistry, req Request) (Result, error) {
	local := Result{SVG: Generate(req.Seed), Seed: req.Seed, Source: SourceLocal}
	if llm == nil {
		return local, nil
	}
	chain, requested, err := chainFor(llm, req)
	if err != nil {
		if req.Model != "" {
			return Result{}, err
		}
		slog.Debug("avatar: no background model, drawing locally", "agent", req.Agent, "error", err)
		return local, nil
	}
	seed := req.Seed
	for attempt := 0; attempt < 2; attempt++ {
		svg, served, err := ask(ctx, llm, chain, requested, req.Agent, seed)
		if err == nil {
			return Result{SVG: svg, Model: served, Seed: seed, Source: SourceModel}, nil
		}
		if ctx.Err() != nil {
			return Result{}, ctx.Err()
		}
		slog.Debug("avatar: model attempt failed", "agent", req.Agent, "attempt", attempt+1, "error", err)
		seed = NextSeed(seed)
	}
	return local, nil
}

// chainFor resolves the chain of a request without Claude Code targets.
func chainFor(llm core.LLMRegistry, req Request) ([]core.LLMTarget, string, error) {
	if req.Model == "" {
		return llmcall.AgentBackgroundChain(llm, req.Config)
	}
	if llmcall.IsClaudeCodeAddress(llm, req.Model) {
		return nil, "", ErrClaudeCodeModel
	}
	chain, err := llmcall.Chain(llm, "", req.Model, nil)
	if err != nil {
		return nil, "", fmt.Errorf("%w: %q", ErrUnknownModel, req.Model)
	}
	rest := llmcall.WithoutClaudeCode(llm, chain)
	if len(rest) == 0 {
		return nil, "", ErrClaudeCodeModel
	}
	return rest, req.Model, nil
}

// ask makes one model call and sanitizes the reply.
func ask(ctx context.Context, llm core.LLMRegistry, chain []core.LLMTarget, requested, agent string, seed int64) (string, string, error) {
	ctx, cancel := context.WithTimeout(ctx, attemptTimeout)
	defer cancel()
	stream, target, err := llmcall.Stream(ctx, llm, chain, core.ChatRequest{
		System:          SystemPrompt,
		Messages:        []core.Message{{Role: core.RoleUser, Content: []core.ContentBlock{{Kind: core.BlockText, Text: Prompt(FamilyFor(seed), seed)}}}},
		MaxTokens:       maxTokens,
		ReasoningEffort: "off",
	}, core.LLMCallMeta{Source: CallSource, Agent: agent, Requested: requested}, nil)
	if err != nil {
		return "", "", err
	}
	var text strings.Builder
	for event, err := range stream {
		if err != nil {
			return "", "", err
		}
		switch event.Kind {
		case core.ChatTextDelta:
			text.WriteString(event.Text)
		case core.ChatBlock:
			if event.Block.Kind == core.BlockText {
				text.WriteString(event.Block.Text)
			}
		}
		if text.Len() > 4*MaxSize {
			return "", "", errors.New("the reply is too long")
		}
	}
	svg, err := Sanitize(text.String())
	if err != nil {
		return "", "", err
	}
	return svg, llmcall.Address(target), nil
}

// NextSeed derives a new seed from seed (splitmix64), kept in 1..2^31-1 so
// it survives a JSON number in any client.
func NextSeed(seed int64) int64 {
	z := uint64(seed) + 0x9e3779b97f4a7c15
	z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
	z = (z ^ (z >> 27)) * 0x94d049bb133111eb
	z ^= z >> 31
	return int64(z%(1<<31-1)) + 1
}

// SystemPrompt is the style guide of a generation (REQ-AVT-002).
const SystemPrompt = `You draw tiny mascot avatars as SVG. Output ONLY the SVG markup, nothing else: no prose, no code fence.

Style guide, follow it exactly:
- Root: <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">. No width, height, style, class, id, defs, gradients, filters, text, or comments.
- Body: ONE closed shape with fill="currentColor" that fills about 70–85% of the box and is roughly centered. A friendly, soft, organic silhouette with rounded corners; slightly imperfect is good. Draw it as a <path> (or an <ellipse>, <circle>, or <rect> with rx). No outline, no stroke.
- Eyes: EXACTLY two eye holes with fill="#FFFFFF", drawn as <ellipse> or as <rect> with rx equal to half the width (a pill). Each eye is about 7–11 units wide and 9–22 units tall. Place both fully on the body, near each other (centers 12–22 units apart), usually a little above or off the body's center so the character looks to one side. Vary them naturally: tilt both eyes the same way with transform="rotate(angle cx cy)", sometimes make one slightly smaller or higher.
- Nothing else: no mouth, no nose, no cheeks, no pupils, no highlights, no shadows, no other colors.
- Allowed elements: svg, g, path, ellipse, circle, rect. Allowed attributes: xmlns, viewBox, d, cx, cy, rx, ry, r, x, y, width, height, fill, transform (rotate, translate, scale only). Keep every coordinate between 0 and 100 and the whole SVG under 2000 characters.`

// familyHints describe each body family to the model.
var familyHints = map[string]string{
	"circle":                "a plump circle",
	"ellipse":               "a wide ellipse, maybe slightly tilted",
	"squircle":              "a squircle: a square with very round corners and slightly bulging sides",
	"tilted rounded square": "a rounded square tilted 25–40 degrees, with soft corners",
	"rounded triangle":      "a rounded triangle pointing up, wide at the bottom, with very soft corners",
	"cloud":                 "a cloud made of 4–5 overlapping round puffs",
	"teardrop":              "a teardrop or pear: a round body with one soft point leaning up to a side",
	"blob":                  "a soft organic blob, like a pebble or a bean",
}

// Prompt is the user message of a generation: the body family and the seed.
func Prompt(family string, seed int64) string {
	hint := familyHints[family]
	if hint == "" {
		hint = family
	}
	return fmt.Sprintf("Draw one avatar. Body shape: %s. Variation seed: %d (use it to vary proportions, tilt, eye size, spacing, and gaze). Output only the SVG.", hint, seed)
}
