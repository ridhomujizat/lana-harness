// Package knowledge keeps lana's knowledge vault: a plain Obsidian-compatible
// folder of sources and wiki pages plus the generated index and log
// (REQ-KNW-001–004, -010–013, -020).
package knowledge

import (
	_ "embed"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"syscall"
	"time"
)

//go:embed templates/KNOWLEDGE.md
var knowledgeTemplate string

// File and folder names of the vault layout (REQ-KNW-002, REQ-KNU-010).
const (
	sourcesDir = "sources"
	wikiDir    = "wiki"
	inboxDir   = "inbox"
	indexFile  = "index.md"
	logFile    = "log.md"
	lockFile   = ".lana.lock"
)

// maxPageRunes is the longest page allowed after a change (REQ-KNW-012).
const maxPageRunes = 40000

// indexHeader is the fixed preamble of the generated catalog (REQ-KNW-004).
const indexHeader = "# Knowledge index\n\nGenerated by lana after each change. Edits here are overwritten.\n"

// logHeader seeds log.md; the file is append-only after that.
const logHeader = "# Knowledge log\n\nAppend-only: lana adds one entry per change and never rewrites this file.\n"

// Vault is one knowledge folder. Writes serialize on an in-process mutex and a
// file lock on <root>/.lana.lock.
type Vault struct {
	root string
	now  func() time.Time

	mu sync.Mutex

	// index, when set, lets SaveSource compare a new source against indexed
	// source hashes before it hashes the files itself (design §2).
	index *Index

	// beforeCommit runs after a write is computed and before the file is
	// re-checked for concurrent edits. It is nil in production and only set by
	// tests.
	beforeCommit func(path string)
}

// Open prepares the vault at root: it creates sources/, wiki/, inbox/, and
// journal/ and seeds KNOWLEDGE.md, index.md, and log.md only when they are
// missing. It never overwrites or deletes a file (AC-KNW-001, REQ-KNU-010).
func Open(root string) (*Vault, error) {
	v := &Vault{root: root, now: time.Now}
	for _, dir := range []string{sourcesDir, wikiDir, inboxDir, journalDir} {
		if err := os.MkdirAll(filepath.Join(root, dir), 0o700); err != nil {
			return nil, err
		}
	}
	for _, seed := range []struct {
		rel     string
		content string
	}{
		{"KNOWLEDGE.md", knowledgeTemplate},
		{indexFile, indexHeader},
		{logFile, logHeader},
	} {
		if err := v.seedFile(seed.rel, seed.content); err != nil {
			return nil, err
		}
	}
	return v, nil
}

// Root returns the vault folder.
func (v *Vault) Root() string { return v.root }

// seedFile writes content to rel only when the file does not exist yet.
func (v *Vault) seedFile(rel, content string) error {
	path := filepath.Join(v.root, rel)
	_, err := os.Stat(path)
	if err == nil {
		return nil
	}
	if !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return writeBytes(path, []byte(content))
}

// AppendJournal appends block to journal/<day>.md under the vault lock,
// creating the file with a "# <day>" header when it is missing. It returns the
// vault-relative path of the journal file (design §2, REQ-KNU-004).
func (v *Vault) AppendJournal(day, block string) (rel string, err error) {
	unlock, err := v.lock()
	if err != nil {
		return "", err
	}
	defer unlock()

	abs := filepath.Join(v.root, journalDir, day+".md")
	data, err := os.ReadFile(abs)
	if errors.Is(err, fs.ErrNotExist) {
		data = []byte("# " + day + "\n")
	} else if err != nil {
		return "", err
	}
	data = append(data, []byte("\n"+strings.TrimRight(block, "\n")+"\n")...)
	if err := writeBytes(abs, data); err != nil {
		return "", err
	}
	return journalDir + "/" + day + ".md", nil
}

// lock takes the in-process mutex and the file lock. The returned function
// releases both.
func (v *Vault) lock() (func(), error) {
	v.mu.Lock()
	f, err := os.OpenFile(filepath.Join(v.root, lockFile), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		v.mu.Unlock()
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		v.mu.Unlock()
		return nil, err
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
		v.mu.Unlock()
	}, nil
}

// rel returns the vault-relative path of abs with forward slashes.
func (v *Vault) rel(abs string) string {
	r, err := filepath.Rel(v.root, abs)
	if err != nil {
		return filepath.ToSlash(abs)
	}
	return filepath.ToSlash(r)
}

// wikiPages reads every markdown page under wiki/, sorted by path.
func (v *Vault) wikiPages() ([]Page, error) {
	root := filepath.Join(v.root, wikiDir)
	var paths []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if strings.HasPrefix(d.Name(), ".") {
			return nil
		}
		if strings.EqualFold(filepath.Ext(p), ".md") {
			paths = append(paths, p)
		}
		return nil
	})
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	sort.Strings(paths)
	pages := make([]Page, 0, len(paths))
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			return nil, err
		}
		pages = append(pages, ParsePage(v.rel(p), string(data)))
	}
	return pages, nil
}

// writeBytes writes data to path atomically with mode 0600: a temp file in the
// same directory, sync, chmod, then rename.
func writeBytes(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+"-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer func() { _ = os.Remove(name) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(name, 0o600); err != nil {
		return err
	}
	return os.Rename(name, path)
}

// regenerateIndex rebuilds index.md from every page under wiki/ (REQ-KNW-004).
func (v *Vault) regenerateIndex() error {
	pages, err := v.wikiPages()
	if err != nil {
		return err
	}
	return writeBytes(filepath.Join(v.root, indexFile), []byte(renderIndex(pages)))
}
