import { ICONS } from "virtual:icons";

/* Inline Lucide icon, matching gr8r-studio's ic(): same wrapper markup and
   stroke width. The virtual module is generated by the lucideSubset Vite plugin
   from the icon names that appear quoted in src/. */
export interface IcProps {
  name: string;
  size?: number;
  className?: string;
}

export function Ic({ name, size = 16, className = "" }: IcProps) {
  const inner =
    ICONS[name] || '<rect x="5" y="5" width="14" height="14" rx="3"/>';
  return (
    <svg
      className={className ? "i " + className : "i"}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: inner }}
    />
  );
}

/* The Lana brand mark (the same asset the old sidebar used), in the slot of
   Gr8r's `.ws-logo`. Dark theme inverts it in gr8r-lana.css. */
export function LanaMark({ size = 22 }: { size?: number }) {
  return (
    <img
      className="lana-mark"
      src="/assets/icons/logo-mark.svg"
      width={size}
      height={size}
      alt=""
      aria-hidden="true"
    />
  );
}
