import { ICONS } from "virtual:icons";

/* Inline Lucide icon, matching gr8r-studio's ic(): same wrapper markup and
   stroke width. The virtual module is generated by the lucideSubset Vite plugin
   from the icon names that appear quoted in src/. */
export interface IcProps {
  name: string;
  size?: number;
  className?: string;
}

export function Ic({ name, size = 16, className = "" }: IcProps) {
  const inner =
    ICONS[name] || '<rect x="5" y="5" width="14" height="14" rx="3"/>';
  return (
    <svg
      className={className ? "i " + className : "i"}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      dangerouslySetInnerHTML={{ __html: inner }}
    />
  );
}

/* The Lana brand mark (the same asset the old sidebar used), in the slot of
   Gr8r's `.ws-logo`. Dark theme inverts it in gr8r-lana.css. */
export function LanaMark({ size = 22 }: { size?: number }) {
  return (
    <img
      className="lana-mark"
      src="/assets/icons/logo-mark.svg"
      width={size}
      height={size}
      alt=""
      aria-hidden="true"
    />
  );
}

/* The Lana mark as pixel art (spec 62 pixel style): the two strokes of the Λ
   as 2 px stair steps on a 12x12 grid, the left stroke fainter as in the
   vector mark. 24 px shows it at exactly 2x. It draws in currentColor, so it
   follows the theme without the invert filter of the image mark. */
const PIXEL_MARK_LEFT = [4, 4, 3, 3, 2, 2, 1, 1, 0, 0];
const PIXEL_MARK_RIGHT = [5, 5, 6, 6, 7, 7, 8, 8, 9, 9];

export function PixelLanaMark({ size = 24 }: { size?: number }) {
  return (
    <svg
      className="lana-mark lana-mark-pixel"
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      <g fill="currentColor" opacity="0.55">
        {PIXEL_MARK_LEFT.map((x, row) => (
          <rect key={row} x={x} y={row + 1} width={3} height={1} />
        ))}
      </g>
      <g fill="currentColor">
        {PIXEL_MARK_RIGHT.map((x, row) => (
          <rect key={row} x={x} y={row + 1} width={3} height={1} />
        ))}
      </g>
    </svg>
  );
}
